"""Measure the maximum ground footprint available at retained composition anchors."""
import re
from common import *
guard()
report=read(OUT/'runtime/evidence/r7-views-after-forward_plus/report.json')
base=read(OUT/'evidence/r1-comparison/r7-views-before-forward_plus/report.json')
def numbers(s):return [float(x) for x in re.findall(r'-?\d+(?:\.\d+)?(?:e[+-]?\d+)?',s)]
def union(rects):
    xs=sorted({r[0] for r in rects}|{r[2] for r in rects});area=0.
    for left,right in zip(xs,xs[1:]):
        spans=sorted((r[1],r[3]) for r in rects if r[0]<right and r[2]>left)
        length=0.;lo=hi=None
        for a,b in spans:
            if lo is None:lo,hi=a,b
            elif a>hi:length+=hi-lo;lo,hi=a,b
            else:hi=max(hi,b)
        if lo is not None:length+=hi-lo
        area+=(right-left)*length
    return area
rows=[]
for view,a,b in zip(report['views'],base['measurements'],report['measurements']):
    centre=numbers(view['at']);cx,cz=centre[0],centre[2];rects=[];count=0
    for name,new in b['cover']['anchors'].items():
        if 'composition' not in new:continue
        old=a['cover']['anchors'][name];box=numbers(old['mesh_bounds']);assert len(box)==6
        for t in old['poses']:
            pts=[]
            for i in range(8):
                v=[box[j]+(box[j+3] if i&(1<<j) else 0) for j in range(3)]
                pts.append([sum(t[j*3+k]*v[j] for j in range(3))+t[9+k] for k in [0,2]])
            x0=max(cx-16,min(p[0] for p in pts));x1=min(cx+16,max(p[0] for p in pts))
            z0=max(cz-16,min(p[1] for p in pts));z1=min(cz+16,max(p[1] for p in pts))
            if x1>x0 and z1>z0:rects.append((x0,z0,x1,z1));count+=1
    area=union(rects)
    rows.append({'view':view['id'],'window_centre':centre,'window_width_m':32,'eligible_root_envelopes_intersecting_window':count,'maximum_aabb_ground_footprint_m2':area,'maximum_aabb_ground_footprint_percent':100*area/1024})
write(OUT/'evidence/retained-coverage-limit.json',{'scope':'Union computed from captured original composition mesh AABB and pose values clipped to a 32 x 32 m XZ window around each matched view target. Includes vertical projection and all retained roots, even hidden/offscreen ones. This is an upper bound on possible local plant coverage, not measured leaf opacity, visible-screen density, terrain area or reference-image segmentation. R7 remains inside these envelopes, including sway. No geometry is generated by this measurement.','views':rows,'proposal_only':{'option_a':'Review this bounded candidate at retained envelopes; accept that its ground cannot form the reference continuous understorey.','option_b':'Separately authorize a 2x horizontal/vertical render-envelope study at the same root poses: tuft 0.300 x 0.158 x 0.296 m to at most 0.600 x 0.317 x 0.592 m; ground fern 0.520 x 0.246 x 0.389 m to at most 1.040 x 0.492 x 0.778 m. Individual XZ envelope area increases at most fourfold before overlap; terrain fit, source sightlines, actual controller clearance and building/excavation masking must be re-evaluated. This is not implemented or accepted.','option_c':'If more roots or continuous terrain dressing is selected instead, commission a separate geography/save-compatibility decision and source-surface fitting work. No new anchors, scatter or topology are present in R7.'}})
print(json.dumps(rows,indent=2))
